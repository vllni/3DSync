#!/usr/bin/env python3
"""Generate source/ui/fontdata.cpp: 4-bit anti-aliased glyph bitmaps for the
on-screen UI.  The fonts themselves are not in the repository; pass the
directories they were unpacked to:

    tools/make_font.py <Inter dir> <JetBrains Mono dir> source/ui/fontdata.cpp

  Inter 4.1           https://github.com/rsms/inter/releases  (extras/otf/)
  JetBrains Mono 2.304 https://github.com/JetBrains/JetBrainsMono/releases (fonts/ttf/)

Both are SIL Open Font License 1.1, which permits embedding rendered glyphs in
a program; the notice is repeated in the generated file.  Needs Pillow.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

# name, directory index, file, pixel size
FONTS = [
    ("kFontSmall", 0, "Inter-Medium.otf", 11),
    ("kFontBody", 0, "Inter-Medium.otf", 13),
    ("kFontBold", 0, "Inter-SemiBold.otf", 14),
    ("kFontTitle", 0, "InterDisplay-Bold.otf", 19),
    ("kFontMono", 1, "JetBrainsMono-Regular.ttf", 11),
]

# Printable ASCII, Latin-1 (save folders are named after game titles, and
# European ones are accented), and the punctuation 3DSync's own messages use.
CODEPOINTS = (list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) +
              [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026])


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    dirs = [sys.argv[1], sys.argv[2]]
    paths = {0: "extras/otf", 1: "fonts/ttf"}
    out = [
        "// Generated by tools/make_font.py -- do not edit.",
        "// Glyphs rendered from Inter (c) The Inter Project Authors and",
        "// JetBrains Mono (c) The JetBrains Mono Project Authors, both under the",
        "// SIL Open Font License 1.1 (https://openfontlicense.org).",
        '#include "font.h"',
        "",
        "namespace ui",
        "{",
        "",
    ]
    for name, d, fname, size in FONTS:
        font = ImageFont.truetype(f"{dirs[d]}/{paths[d]}/{fname}", size)
        ascent, descent = font.getmetrics()
        bits = bytearray()
        glyphs = []
        for cp in CODEPOINTS:
            ch = chr(cp)
            adv = round(font.getlength(ch))
            x0, y0, x1, y1 = font.getbbox(ch)
            w, h = max(0, x1 - x0), max(0, y1 - y0)
            off = len(bits)
            if w and h:
                img = Image.new("L", (w, h), 0)
                ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
                levels = [(v * 15 + 127) // 255 for v in img.getdata()]
                if len(levels) % 2:
                    levels.append(0)
                for i in range(0, len(levels), 2):
                    bits.append(levels[i] | (levels[i + 1] << 4))
            glyphs.append((cp, x0, y0, w, h, adv, off))
        out.append(f"static const uint8_t {name}Bits[] = {{")
        for i in range(0, len(bits), 20):
            out.append("    " + ", ".join(str(b) for b in bits[i:i + 20]) + ",")
        out.append("};")
        out.append(f"static const Glyph {name}Glyphs[] = {{")
        for g in glyphs:
            out.append("    {%d, %d, %d, %d, %d, %d, %d}," % g)
        out.append("};")
        out.append(f"const Font {name} = {{{ascent + descent}, {ascent}, {name}Glyphs, "
                   f"{len(glyphs)}, {name}Bits}};")
        out.append("")
    out.append("} // namespace ui")
    out.append("")
    with open(sys.argv[3], "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
